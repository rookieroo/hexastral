export function toHant(s: string): string {
  return s
    .split('')
    .map((c) => S2T[c] ?? c)
    .join('')
}

const T2S: Record<string, string> = Object.fromEntries(
  Object.entries(S2T).map(([s, t]) => [t, s])
)

/** 繁体 → 简体（用于 en/ja 术语卡对繁体输入的归一）。 */
