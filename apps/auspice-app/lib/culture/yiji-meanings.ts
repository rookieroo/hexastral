const TERM_PINYIN: Record<string, string> = PY
const TERM_EN: Record<string, string> = EN
const TERM_JA: Record<string, string> = JA

export function yijiTermPinyin(term: string): string | null {
  return TERM_PINYIN[term] ?? TERM_PINYIN[toHant(term)] ?? TERM_PINYIN[toHans(term)] ?? null
}

/** 取释义（四语）：zh 原文简/繁；en = 拼音 + 英文释义（无则原文+拼音）；
 *  ja = 日文释义（无则原文）。 */
export function yijiMeaning(term: string, locale: string): string | null {
  if (locale.startsWith('zh-Hant') || locale.includes('hant')) {
    return MEANINGS_ZH_HANT[term] ?? MEANINGS_ZH_HANT[toHant(term)] ?? null
  }
  if (locale.startsWith('ja')) {
    return (
      TERM_JA[term] ??
      TERM_JA[toHant(term)] ??
      TERM_JA[toHans(term)] ??
      MEANINGS_ZH_HANS[term] ??
      null
    )
  }
  if (locale.startsWith('en')) {
    const pinyin = TERM_PINYIN[term] ?? TERM_PINYIN[toHant(term)] ?? TERM_PINYIN[toHans(term)]
    const en = TERM_EN[term] ?? TERM_EN[toHant(term)] ?? TERM_EN[toHans(term)]
    if (en && pinyin) return `${pinyin} · ${en}`
    const hans = MEANINGS_ZH_HANS[term] ?? MEANINGS_ZH_HANS[toHans(term)]
    return pinyin ? `${pinyin} · ${hans ?? term}` : (en ?? hans ?? null)
  }
  return MEANINGS_ZH_HANS[term] ?? null
}

export const hasYijiMeaning = (term: string): boolean => term in MEANINGS_ZH_HANS
